#include <assert.h>
int main(){
 nbt::FavouritePress s;uint8_t p[8]={0};
 p[2]=1;assert(!s.feed(0x15,0xc,0xc02,0xc,p,8));
 for(unsigned n=1;n<=12;++n){
  p[2]=2;assert(s.feed(0x15,0xc,0xc02,0xc,p,8));assert(s.serial==n&&s.last==4);
  assert(!s.feed(0x15,0xc,0xc02,0xc,p,8));assert(s.serial==n);
  p[2]=1;assert(!s.feed(0x15,0xc,0xc02,0xc,p,8));
 }
 p[2]=0;s.feed(0x15,0xc,0xc02,0xc,p,8);p[2]=2;
 assert(!s.feed(0x15,0xc,0xc02,0,p,8));assert(!s.feed(0x15,0xc,0xc02,0xc,p,7));
 p[7]=3;assert(!s.feed(0x15,0xc,0xc02,0xc,p,8));assert(s.serial==12&&s.pressed==0);
 p[7]=0;assert(s.feed(0x15,0xc,0xc02,0xc,p,8));assert(s.serial==13);
}

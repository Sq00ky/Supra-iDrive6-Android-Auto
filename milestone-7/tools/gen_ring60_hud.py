"""Pack the approved native ring artwork; the daemon needs no curve or font library."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    art = json.loads((ROOT / "tools/hud_ring60_design.json").read_text())
    lines = [
        "// SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0",
        "// Required Notice: Copyright (c) 2026 nanaisu - NBT-AAD (https://github.com/Sq00ky/Supra-iDrive6-Android-Auto)",
        "// Generated by tools/gen_ring60_hud.py from approved native artwork. Do not edit.",
        "#ifndef CLUSTER_HUD_RING60_DATA_HPP", "#define CLUSTER_HUD_RING60_DATA_HPP",
        "#include <stdint.h>", "namespace nbt { namespace hudterm { namespace ring60 {",
        "struct NativePoint { int8_t x, y; };",
        "struct Outline { const NativePoint* points; uint8_t count; };",
    ]

    def points(name, values):
        assert all(-127 <= v <= 127 for p in values for v in p)
        rows = ["{%d,%d}" % tuple(p) for p in values]
        lines.append("static const NativePoint %s[] = {%s};" % (name, ",".join(rows)))

    for name in ("outer", "inner"):
        points("k" + name.title(), art[name])
        assert len(art[name + "_index"]) == 361
        assert all(0 <= i < len(art[name]) for i in art[name + "_index"])
        lines.append("static const uint8_t k%sIndex[] = {%s};" % (
            name.title(), ",".join(map(str, art[name + "_index"])) ))
    for i, p in enumerate(art["circulation"]):
        points("kCirculation%d" % i, p)
    lines.append("static const Outline kCirculation[] = {%s};" % ",".join(
        "{kCirculation%d,%d}" % (i, len(p)) for i, p in enumerate(art["circulation"])))
    assert len(art["exit_heads"]) == len(art["placement"]) == 301
    assert all(len(p) == 7 for p in art["exit_heads"])
    lines.append("static const NativePoint kExits[301][7] = {")
    for p in art["exit_heads"]:
        assert all(-127 <= v <= 127 for xy in p for v in xy)
        lines.append("    {%s}," % ",".join("{%d,%d}" % tuple(xy) for xy in p))
    lines.append("};")
    points("kPlacement", art["placement"])
    points("kReturn", art["return_head"])
    lines += ["enum { kReturnCenterY = %d, kReturnEntryEnd = %d };" % (
        art["return_center_y"], art["return_entry_end"]), "} } }", "#endif", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "src/cluster/hud_ring60_data.hpp"
    content = generate()
    if args.check:
        if target.read_text() != content:
            parser.exit(1, "ring60 data is stale; run tools/gen_ring60_hud.py\n")
    else:
        target.write_text(content)

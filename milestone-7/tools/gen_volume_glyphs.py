"""Writes src/volume_glyphs.hpp: the volume pill's speaker and labels as 8-bit alpha bitmaps, one set per pill scale.

    python3 tools/gen_volume_glyphs.py --font Inter-Regular.ttf --out src/volume_glyphs.hpp

Needs Pillow. Font: Inter 4.1 Regular (https://github.com/rsms/inter, SIL OFL 1.1), extras/ttf/Inter-Regular.ttf.
"""
import argparse

from PIL import Image, ImageDraw, ImageFont

SCALES = [0.8, 1.0, 1.2, 1.4, 1.6]   # the pill's scale range (volume_pill.cpp)
ICON_REF = 30                        # px at scale 1
LABEL_REF = 21
ICON_SIZES = [int(ICON_REF * s + 0.5) for s in SCALES]
LABEL_SIZES = [int(LABEL_REF * s + 0.5) for s in SCALES]
WORDS = [("entertainment", "Entertainment"), ("navigation", "Navigation")]
SPEAKER = [(4, 9), (8, 9), (14, 4), (14, 20), (8, 15), (4, 15)]   # 24-unit box, outline
STROKE = 1.6
SS = 16


def speaker(px):
    big = px * SS
    k = big / 24.0
    im = Image.new("L", (big, big), 0)
    pts = [(x * k, y * k) for x, y in SPEAKER]
    ImageDraw.Draw(im).line(pts + pts[:2], fill=255, width=int(round(STROKE * k)), joint="curve")
    return list(im.resize((px, px), Image.BOX).tobytes())


def word(font_path, px, text):
    font = ImageFont.truetype(font_path, px)
    ascent, descent = font.getmetrics()
    x0, _, x1, _ = font.getbbox(text)
    w, h = x1 - x0, ascent + descent
    im = Image.new("L", (w, h), 0)
    ImageDraw.Draw(im).text((-x0, 0), text, font=font, fill=255)
    return w, h, list(im.tobytes())


def array(name, data):
    rows = []
    for i in range(0, len(data), 24):
        rows.append("    " + ", ".join(str(v) for v in data[i:i + 24]))
    return "static const unsigned char %s[%d] = {\n%s\n};\n" % (name, len(data), ",\n".join(rows))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", required=True)
    ap.add_argument("--out", default="src/volume_glyphs.hpp")
    a = ap.parse_args()

    out = ["// Generated by tools/gen_volume_glyphs.py from Inter 4.1 Regular (SIL OFL 1.1). Do not hand-edit.",
           "// Speaker: outline in a 24-unit box at each size in kVolIcons. Labels: one bitmap per word, as high",
           "// as the font's ascent + descent so both words share a baseline, trimmed to the ink left and right.",
           "#ifndef NBT_VOLUME_GLYPHS_HPP",
           "#define NBT_VOLUME_GLYPHS_HPP",
           "",
           "struct VolBitmap { unsigned short w, h; const unsigned char* alpha; };",
           "struct VolIcon { int px; const unsigned char* alpha; };",
           "struct VolLabelSet { int px; VolBitmap entertainment, navigation; };",
           "",
           "static const int kVolIconRef = %d;    // px at pill scale 1" % ICON_REF,
           "static const int kVolLabelRef = %d;" % LABEL_REF,
           ""]
    for px in ICON_SIZES:
        out.append(array("kIcon_%d" % px, speaker(px)))
    out.append("static const VolIcon kVolIcons[%d] = {" % len(ICON_SIZES))
    out += ["    { %d, kIcon_%d }," % (px, px) for px in ICON_SIZES]
    out += ["};", "static const int kVolIconCount = %d;" % len(ICON_SIZES), ""]

    sets = []
    for px in LABEL_SIZES:
        dims = []
        for key, text in WORDS:
            w, h, data = word(a.font, px, text)
            out.append(array("kLabel_%d_%s" % (px, key), data))
            dims.append("{ %d, %d, kLabel_%d_%s }" % (w, h, px, key))
        sets.append("    { %d, %s, %s }," % (px, dims[0], dims[1]))
    out.append("static const VolLabelSet kVolLabels[%d] = {" % len(LABEL_SIZES))
    out += sets
    out += ["};", "static const int kVolLabelCount = %d;" % len(LABEL_SIZES), "", "#endif", ""]

    with open(a.out, "w", newline="\n") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()

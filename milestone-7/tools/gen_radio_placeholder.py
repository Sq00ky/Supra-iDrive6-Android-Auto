"""Writes src/radio/radio_placeholder_art.hpp: the neutral radio picture of the Android Auto media tile (408 x 457 JPEG).

    python3 tools/gen_radio_placeholder.py --out src/radio/radio_placeholder_art.hpp [--jpeg preview.jpg]

Needs Pillow.
"""
import argparse
import io
import sys

from PIL import Image, ImageDraw

W, H = 408, 457
SS = 4
MAX_BYTES = 10240
TOP, BOTTOM = (0x2e, 0x39, 0x46), (0x16, 0x1b, 0x21)
LINE = (0xa9, 0xb6, 0xc3)
OPACITY = 0.55
STROKE = 6.5

BODY = (120, 114, 288, 221)
BODY_RADIUS = 16
KNOB = (168.5, 169, 27.4)
ANTENNA = ((155.7, 114.2), (239.5, 69.2))
SCALE_X = (223.3, 265.2)
SCALE_Y = (146.5, 169, 191.5)


def gradient():
    im = Image.new("RGB", (W * SS, H * SS))
    d = ImageDraw.Draw(im)
    for y in range(H * SS):
        t = y / float(H * SS - 1)
        d.line([(0, y), (W * SS, y)], fill=tuple(int(round(a + (b - a) * t)) for a, b in zip(TOP, BOTTOM)))
    return im


def outline():
    """The radio as a coverage mask."""
    m = Image.new("L", (W * SS, H * SS), 0)
    d = ImageDraw.Draw(m)
    w = int(round(STROKE * SS))

    def px(v):
        return v * SS

    def cap(x, y):
        r = w / 2.0
        d.ellipse([x - r, y - r, x + r, y + r], fill=255)

    def line(p, q):
        d.line([(px(p[0]), px(p[1])), (px(q[0]), px(q[1]))], fill=255, width=w)
        cap(px(p[0]), px(p[1]))
        cap(px(q[0]), px(q[1]))

    x0, y0, x1, y1 = [px(v) for v in BODY]
    d.rounded_rectangle([x0 - w / 2.0, y0 - w / 2.0, x1 + w / 2.0, y1 + w / 2.0], radius=px(BODY_RADIUS) + w / 2.0, fill=255)
    d.rounded_rectangle([x0 + w / 2.0, y0 + w / 2.0, x1 - w / 2.0, y1 - w / 2.0], radius=max(px(BODY_RADIUS) - w / 2.0, 0), fill=0)
    cx, cy, r = [px(v) for v in KNOB]
    d.ellipse([cx - r - w / 2.0, cy - r - w / 2.0, cx + r + w / 2.0, cy + r + w / 2.0], fill=255)
    d.ellipse([cx - r + w / 2.0, cy - r + w / 2.0, cx + r - w / 2.0, cy + r - w / 2.0], fill=0)
    line(*ANTENNA)
    for y in SCALE_Y:
        line((SCALE_X[0], y), (SCALE_X[1], y))
    return m


def render():
    base = gradient()
    mask = outline().point(lambda v: int(v * OPACITY))
    base.paste(Image.new("RGB", base.size, LINE), (0, 0), mask)
    return base.resize((W, H), Image.LANCZOS)


def jpeg(im):
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=85, optimize=True, progressive=False)
    return buf.getvalue()


def header(data):
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + ", ".join("0x%02x" % v for v in data[i:i + 16]))
    return "\n".join([
        "// SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0",
        "// Required Notice: Copyright (c) 2026 nanaisu - NBT-AAD (https://github.com/Sq00ky/Supra-iDrive6-Android-Auto)",
        "// Generated by tools/gen_radio_placeholder.py, do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "namespace nbt {",
        "",
        "// Neutral radio picture, %d x %d JPEG." % (W, H),
        "static const uint8_t kRadioPlaceholderJpeg[] = {",
        ",\n".join(rows),
        "};",
        "",
        "}  // namespace nbt",
        ""])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="src/radio/radio_placeholder_art.hpp")
    ap.add_argument("--jpeg")
    a = ap.parse_args()

    data = jpeg(render())
    if len(data) > MAX_BYTES:
        sys.exit("JPEG is %d bytes, limit %d" % (len(data), MAX_BYTES))
    if a.jpeg:
        with open(a.jpeg, "wb") as f:
            f.write(data)
    with open(a.out, "w", newline="\n") as f:
        f.write(header(data))
    print("%d bytes" % len(data))


if __name__ == "__main__":
    main()

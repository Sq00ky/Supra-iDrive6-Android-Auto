"""Generate the fixed F30 artwork. Only this build-time tool uses floating point."""
import argparse,json,math
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def rounded(x):return int(math.floor(x+.5))if x>=0 else -int(math.floor(-x+.5))
def cross(a,b,c):return(b[0]-a[0])*(c[1]-b[1])-(b[1]-a[1])*(c[0]-b[0])
def clean(points):
 out=[]
 for x,y in points:
  p=(rounded(x),rounded(y))
  if not out or p!=out[-1]:out.append(p)
 if len(out)>1 and out[0]==out[-1]:out.pop()
 changed=True
 while changed and len(out)>3:
  changed=False
  for i in range(len(out)):
   if cross(out[i-1],out[i],out[(i+1)%len(out)])==0:
    out.pop(i);changed=True;break
 return out

def on(a,b,p):
 return cross(a,b,p)==0 and min(a[0],b[0])<=p[0]<=max(a[0],b[0]) and min(a[1],b[1])<=p[1]<=max(a[1],b[1])

def valid(poly):
 assert 3<=len(poly)<=99 and len(set(poly))==len(poly),poly
 for i,a in enumerate(poly):
  b=poly[(i+1)%len(poly)]
  for j in range(i+2,len(poly)):
   if i==0 and j==len(poly)-1:continue
   c,d=poly[j],poly[(j+1)%len(poly)]
   assert not((cross(a,b,c)*cross(a,b,d)<0 and cross(c,d,a)*cross(c,d,b)<0) or on(a,b,c) or on(a,b,d) or on(c,d,a) or on(c,d,b)),poly

def outset(poly,width):
 out=[]
 for i,b in enumerate(poly):
  a,c=poly[i-1],poly[(i+1)%len(poly)]
  u=(b[0]-a[0],b[1]-a[1]);v=(c[0]-b[0],c[1]-b[1])
  lu,lv=math.hypot(*u),math.hypot(*v);u=(u[0]/lu,u[1]/lu);v=(v[0]/lv,v[1]/lv)
  n0=(u[1],-u[0]);n1=(v[1],-v[0])
  if cross(a,b,c)>0:
   start=math.atan2(n0[1],n0[0]);span=(math.atan2(n1[1],n1[0])-start)%(2*math.pi)
   steps=max(1,math.ceil(span/(math.pi/4)))
   out.extend((b[0]+width*math.cos(start+span*k/steps),b[1]+width*math.sin(start+span*k/steps))for k in range(steps+1))
  else:
   den=1+u[0]*v[0]+u[1]*v[1];assert den>.01
   out.append((b[0]+width*(n0[0]+n1[0])/den,b[1]+width*(n0[1]+n1[1])/den))
 return clean(out)

def clip_y(poly,low,high):
 out=[tuple(p)for p in poly]
 for boundary,above in ((low,True),(high,False)):
  src=out;out=[]
  if not src:break
  a=src[-1];ain=a[1]>=boundary if above else a[1]<=boundary
  for b in src:
   bin_=b[1]>=boundary if above else b[1]<=boundary
   if ain!=bin_:
    t=(boundary-a[1])/(b[1]-a[1]);out.append((a[0]+t*(b[0]-a[0]),boundary))
   if bin_:out.append(b)
   a,ain=b,bin_
 return clean(out)

def generate():
 design=json.loads((ROOT/'tools/hud_unified_design.json').read_text())
 out=['// SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0',
      '// Required Notice: Copyright (c) 2026 nanaisu - NBT-AAD (https://github.com/Sq00ky/Supra-iDrive6-Android-Auto)',
      '// Generated by tools/gen_unified_hud.py from the accepted integer artwork. Do not edit.',
      '#ifndef CLUSTER_HUD_UNIFIED_DATA_HPP','#define CLUSTER_HUD_UNIFIED_DATA_HPP',
      '#include "cluster/hudterm_shapes.hpp"','namespace nbt { namespace hudterm { namespace unified {',
      'struct Outline { const Point* points; uint8_t count, tailStart; };',
      'struct Road { Outline edge, fill; };',
      'struct Glyph { Outline body, head, bodyEdge, headEdge, hole; const Road* farRoads; uint8_t farCount; const Road* nearRoads; uint8_t nearCount; int16_t farTail, nearTail, curveY; };',
      'struct Lane { Outline body, head; };']
 def emit(name,poly,glyph=None):
  if not poly:return '{0,0,0}'
  p=clean(poly);valid(p);start=len(p)
  if glyph and glyph['aa_type']!=39:
   flags=[y>=glyph['far_tail'] and abs(x-glyph['stem_x'])<=7 for x,y in p]
   if any(flags):
    first=next(i for i,v in enumerate(flags)if not v);p=p[first:]+p[:first];flags=flags[first:]+flags[:first]
    start=flags.index(True);assert flags==[False]*start+[True]*(len(flags)-start),(name,flags)
  out.append('static const Point '+name+'[] = { '+', '.join('{%d,%d}'%q for q in p)+' };')
  return '{%s,%d,%d}'%(name,len(p),start)
 glyphs=[]
 for g in design['glyphs']:
  name='kGlyph'+str(g['aa_type']);body=emit(name+'Body',g['body'],g)
  head=emit(name+'Head',g['head']);hole=emit(name+'Hole',list(reversed(g['hole']))if g.get('hole')else None)
  edge=emit(name+'BodyEdge',outset(g['body'],1),g)if g['aa_type']!=39 else '{0,0,0}'
  he=emit(name+'HeadEdge',outset(g['head'],1))if g['head']else'{0,0,0}'
  roads=[]
  for near in (False,True):
   road_data=[]
   for i,p in enumerate(g['near_roads'if near else'far_roads']):
    e=outset(p,2)
    if not near:p=clip_y(p,14,g['far_road_clip']);e=clip_y(e,14,g['far_road_clip'])
    key=name+('Near'if near else'Far')+str(i)
    road_data.append('{'+emit(key+'Edge',e)+','+emit(key+'Fill',p)+'}')
   if road_data:
    key=name+('NearRoads'if near else'FarRoads');out.append('static const Road '+key+'[] = { '+', '.join(road_data)+' };');roads.extend([key,str(len(road_data))])
   else:roads.extend(['0','0'])
  glyphs.append('{'+','.join([body,head,edge,he,hole]+roads+[str(g.get(k,0))for k in ('far_tail','near_tail','curve_y')])+'}')
 out.append('static const Glyph kGlyphs[] = {\n    '+',\n    '.join(glyphs)+'\n};')
 lanes=[]
 for lane in design['lanes']:
  key='kLane'+str(lane['shape']);lanes.append('{'+emit(key+'Body',lane['body'])+','+emit(key+'Head',lane['head'])+'}')
 out.append('static const Lane kLanes[] = { '+', '.join(lanes)+' };')
 out.extend(['}}} // namespace nbt::hudterm::unified','#endif',''])
 return '\n'.join(out)

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
 target=ROOT/'src/cluster/hud_unified_data.hpp';text=generate()
 if a.check:
  assert target.read_text()==text,'Regenerate src/cluster/hud_unified_data.hpp';print('Unified HUD artwork is current')
 else:target.write_text(text)
if __name__=='__main__':main()
